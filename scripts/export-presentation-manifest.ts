import {createHash} from "node:crypto";
import {mkdir,readFile,writeFile} from "node:fs/promises";
import {dirname,resolve} from "node:path";
import {fileURLToPath} from "node:url";
import {defaultManifest} from "../clients/default/manifest.ts";
import {demoGalleryManifest} from "../clients/demo-gallery/manifest.ts";

export function canonicalJson(value:unknown):string{
  if(Array.isArray(value))return "["+value.map(canonicalJson).join(",")+"]";
  if(value!==null&&typeof value==="object")return "{"+Object.keys(value).sort().map(key=>JSON.stringify(key)+":"+canonicalJson((value as Record<string,unknown>)[key])).join(",")+"}";
  const result=JSON.stringify(value);if(result===undefined)throw new Error("Manifest must contain JSON values only");return result;
}
function checkDepth(value:unknown,depth=0):void{
  if(depth>16)throw new Error("Manifest exceeds depth 16");
  if(value&&typeof value==="object")for(const child of Object.values(value))checkDepth(child,depth+1);
}
export async function exportManifests(check=false,outputDirectory?:string){
  const root=fileURLToPath(new URL("../",import.meta.url)),outputs=new Map<string,string>();
  const hashes:Record<string,string>={};
  for(const manifest of [defaultManifest,demoGalleryManifest]){
    checkDepth(manifest);const canonical=canonicalJson(manifest);
    if(Buffer.byteLength(canonical)>1048576)throw new Error("Manifest exceeds 1 MiB");
    hashes[manifest.profileId]=createHash("sha256").update(canonical).digest("hex");
    outputs.set(resolve(outputDirectory??resolve(root,"clients/manifests"),manifest.profileId+".json"),canonical+"\n");
  }
  if(!outputDirectory)outputs.set(resolve(root,"clients/manifests/fingerprints.generated.ts"),"// Generated by scripts/export-presentation-manifest.ts.\nexport const manifestFingerprints = "+JSON.stringify(hashes,null,2)+" as const;\n");
  for(const [file,content] of outputs){if(check){if(await readFile(file,"utf8")!==content)throw new Error("Presentation manifest drift: "+file);}else{await mkdir(dirname(file),{recursive:true});await writeFile(file,content);}}
  return hashes;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const target=process.argv.find(arg=>arg.startsWith("--output="))?.slice(9);
  console.log(await exportManifests(process.argv.includes("--check"),target));
}
